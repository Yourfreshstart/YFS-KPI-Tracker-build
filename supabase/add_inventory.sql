-- Inventory page: supplies, weekly counts, order quick picks, sent orders.
-- Also loads the last 6 months of counts from the inventory spreadsheet
-- (May 10 - Nov 9, 2026). Odd decimals were rounded UP to the next quarter
-- (2.15 -> 2.25); "restocked" comes from the sheet's "Items Purchased" rows.
-- Usage is never stored -- the app works it out from the counts
-- (last count + restocked - this count), so it always matches the counts.
-- Run once in Supabase: Project -> SQL Editor -> New query -> paste -> Run.

create table if not exists inventory_supplies (
  id bigint generated always as identity primary key,
  name text not null unique,
  unit text not null check (unit in ('gal', 'bottle', 'can', 'box', 'bag')),
  sort_order int not null default 0,
  status text not null default 'active' check (status in ('active', 'retired')),
  -- Quiet start: counts before this date are ignored when working out the
  -- supply's normal amount, and it isn't flagged until 4 weeks after it.
  learn_from date,
  retired_at date,
  -- Kept when a supply is retired (its counts are deleted): about how much
  -- one technician used per week.
  retired_per_tech_week numeric,
  created_at timestamptz not null default now()
);

create table if not exists inventory_counts (
  id bigint generated always as identity primary key,
  count_date date not null,
  supply_id bigint not null references inventory_supplies(id) on delete cascade,
  on_shelf numeric check (on_shelf >= 0),
  restocked numeric not null default 0 check (restocked >= 0),
  entered_by text,
  updated_at timestamptz not null default now(),
  unique (count_date, supply_id)
);
create index if not exists inventory_counts_date_idx on inventory_counts (count_date);

create table if not exists inventory_order_picks (
  name text primary key,
  created_at timestamptz not null default now()
);

create table if not exists inventory_orders (
  id bigint generated always as identity primary key,
  sent_at timestamptz not null default now(),
  sent_by text,
  items jsonb not null
);

-- Same lock-down as every other table: only the server's secret key can read/write.
alter table inventory_supplies enable row level security;
alter table inventory_counts enable row level security;
alter table inventory_order_picks enable row level security;
alter table inventory_orders enable row level security;
revoke all on inventory_supplies, inventory_counts, inventory_order_picks, inventory_orders from anon, authenticated;

